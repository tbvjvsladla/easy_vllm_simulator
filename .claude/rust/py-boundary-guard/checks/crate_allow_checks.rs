//! crate_allow (plan 26111805 D2·D9, cell c20): temporary git repositories with tracked locks, an allowlist, a notice
//! and a fake Cargo home; the real binary, its exit code (0/1/2) and its finding lines.
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn bin() -> &'static str {
    env!("CARGO_BIN_EXE_crate_allow")
}

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";
const ALLOW_REL: &str = ".claude/rust/py-boundary-guard/crate_allowlist.tsv";
const NOTICE_REL: &str = ".claude/rust/py-boundary-guard/notices/NOTICE-crates.md";
const HOME_REL: &str = ".claude/runtime/rust/cargo";
const HEADER: &str = "crate\tversion\tlicense\ttransitive\tscope\tuse\treason\n";

struct Repo(PathBuf);
impl Drop for Repo {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn write(dir: &Path, rel: &str, body: &str) {
    let p = dir.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, body).unwrap();
}

fn git(dir: &Path, args: &[&str]) {
    let s = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(args)
        .status()
        .unwrap();
    assert!(s.success(), "git {args:?}");
}

fn lock(packages: &[(&str, &str, Option<&str>)]) -> String {
    let mut text = "# This file is automatically @generated by Cargo.\nversion = 4\n".to_string();
    for (name, version, source) in packages {
        text.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n"
        ));
        if let Some(s) = source {
            text.push_str(&format!("source = \"{s}\"\nchecksum = \"00\"\n"));
        }
    }
    text
}

fn downloaded(dir: &Path, name: &str, version: &str, license: &str) {
    write(
        dir,
        &format!("{HOME_REL}/registry/src/index.crates.io-0000000000000000/{name}-{version}/Cargo.toml"),
        &format!("[package]\nname = \"{name}\"\nversion = \"{version}\"\nlicense = \"{license}\"\n\n[dependencies.x]\nversion = \"1\"\n"),
    );
}

fn notice(rows: &[(&str, &str, &str)]) -> String {
    let mut text = "# Crate notice\n\n| crate | version | license | used by |\n|---|---|---|---|\n"
        .to_string();
    for (n, v, l) in rows {
        text.push_str(&format!("| {n} | {v} | {l} | test |\n"));
    }
    text
}

/// A repository whose one tracked lock pins `syn 3.0.9` (and a path package), fully listed, noticed and downloaded.
fn clean_repo(name: &str) -> Repo {
    let dir = std::env::temp_dir().join(format!("crate-allow-{}-{}", name, std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    git(&dir, &["init", "-q"]);
    write(
        &dir,
        "a/Cargo.lock",
        &lock(&[("a", "0.1.0", None), ("syn", "3.0.9", Some(CRATES_IO))]),
    );
    write(
        &dir,
        ALLOW_REL,
        &format!("# test\n{HEADER}syn\t3.0.9\tMIT OR Apache-2.0\t3\truntime\tscan\tc10\n"),
    );
    write(
        &dir,
        NOTICE_REL,
        &notice(&[("syn", "3.0.9", "MIT OR Apache-2.0")]),
    );
    downloaded(&dir, "syn", "3.0.9", "MIT OR Apache-2.0");
    git(&dir, &["add", "a/Cargo.lock"]);
    Repo(dir)
}

fn check(repo: &Repo) -> Output {
    Command::new(bin())
        .args(["check", "--repo"])
        .arg(&repo.0)
        .output()
        .unwrap()
}

fn stdout(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned()
}

fn assert_violation(out: &Output, kind: &str, id: &str) {
    let text = stdout(out);
    assert_eq!(out.status.code(), Some(1), "{text}");
    assert!(
        text.lines()
            .any(|l| l.starts_with(&format!("DEPS-VIOLATION {kind} {id}"))),
        "{kind} {id} not in:\n{text}"
    );
    assert!(!text.contains("DEPS-ALLOW-PASS"), "{text}");
}

#[test]
fn listed_noticed_and_downloaded_release_passes_with_the_marker_last() {
    let repo = clean_repo("pass");
    let out = check(&repo);
    let text = stdout(&out);
    assert_eq!(
        out.status.code(),
        Some(0),
        "{text}{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert_eq!(text.lines().last(), Some("DEPS-ALLOW-PASS"));
    assert!(
        text.contains("1 tracked Cargo.lock · 1 external releases pinned"),
        "{text}"
    );
}

#[test]
fn unlisted_release_fails() {
    let repo = clean_repo("unlisted");
    write(
        &repo.0,
        "a/Cargo.lock",
        &lock(&[
            ("syn", "3.0.9", Some(CRATES_IO)),
            ("quote", "1.0.47", Some(CRATES_IO)),
        ]),
    );
    downloaded(&repo.0, "quote", "1.0.47", "MIT OR Apache-2.0");
    assert_violation(&check(&repo), "unlisted", "quote@1.0.47");
}

#[test]
fn other_version_than_the_allowlist_fails() {
    let repo = clean_repo("version");
    write(
        &repo.0,
        "a/Cargo.lock",
        &lock(&[("syn", "3.0.10", Some(CRATES_IO))]),
    );
    downloaded(&repo.0, "syn", "3.0.10", "MIT OR Apache-2.0");
    let out = check(&repo);
    assert_violation(&out, "unlisted", "syn@3.0.10");
    assert!(stdout(&out).contains("only 3.0.9"), "{}", stdout(&out));
}

#[test]
fn untracked_lock_is_not_read() {
    let repo = clean_repo("untracked");
    write(
        &repo.0,
        "b/Cargo.lock",
        &lock(&[("quote", "1.0.47", Some(CRATES_IO))]),
    );
    assert_eq!(check(&repo).status.code(), Some(0));
}

#[test]
fn copyleft_only_license_is_denied() {
    let repo = clean_repo("denied");
    write(
        &repo.0,
        ALLOW_REL,
        &format!("{HEADER}syn\t3.0.9\tGPL-3.0-only\t3\truntime\tscan\tc10\n"),
    );
    write(
        &repo.0,
        NOTICE_REL,
        &notice(&[("syn", "3.0.9", "GPL-3.0-only")]),
    );
    downloaded(&repo.0, "syn", "3.0.9", "GPL-3.0-only");
    assert_violation(&check(&repo), "license-denied", "syn@3.0.9");
}

#[test]
fn malformed_license_expression_is_a_finding() {
    let repo = clean_repo("invalid");
    write(
        &repo.0,
        ALLOW_REL,
        &format!("{HEADER}syn\t3.0.9\tMIT OR\t3\truntime\tscan\tc10\n"),
    );
    assert_violation(&check(&repo), "license-invalid", "syn@3.0.9");
}

#[test]
fn allowlist_license_must_equal_the_downloaded_manifest() {
    let repo = clean_repo("mismatch");
    downloaded(&repo.0, "syn", "3.0.9", "MIT");
    assert_violation(&check(&repo), "license-mismatch", "syn@3.0.9");
}

#[test]
fn pinned_release_without_downloaded_source_fails_closed() {
    let repo = clean_repo("nosource");
    std::fs::remove_dir_all(repo.0.join(HOME_REL)).unwrap();
    assert_violation(&check(&repo), "no-source", "syn@3.0.9");
}

#[test]
fn approved_but_unpinned_release_needs_no_download() {
    let repo = clean_repo("ahead");
    let rows = format!("{HEADER}syn\t3.0.9\tMIT OR Apache-2.0\t3\truntime\tscan\tc10\nyaml-rust2\t0.13.0\tMIT OR Apache-2.0\t4\truntime\tyaml\tc30\n");
    write(&repo.0, ALLOW_REL, &rows);
    let out = check(&repo);
    assert_eq!(out.status.code(), Some(0), "{}", stdout(&out));
    assert!(
        stdout(&out).contains("allowlist 2 rows (1 not pinned by any lock)"),
        "{}",
        stdout(&out)
    );
}

#[test]
fn pinned_release_needs_a_notice_row_with_the_same_license() {
    let repo = clean_repo("notice");
    write(&repo.0, NOTICE_REL, &notice(&[]));
    assert_violation(&check(&repo), "no-notice", "syn@3.0.9");
    write(&repo.0, NOTICE_REL, &notice(&[("syn", "3.0.9", "MIT")]));
    assert_violation(&check(&repo), "notice-license", "syn@3.0.9");
}

#[test]
fn git_source_is_refused_even_when_listed() {
    let repo = clean_repo("git");
    write(
        &repo.0,
        "a/Cargo.lock",
        &lock(&[("syn", "3.0.9", Some("git+https://example.invalid/syn#0"))]),
    );
    assert_violation(&check(&repo), "source", "syn@3.0.9");
}

#[test]
fn input_errors_exit_2() {
    let repo = clean_repo("input");
    write(&repo.0, ALLOW_REL, "crate\tversion\nsyn\t3.0.9\n");
    let out = check(&repo);
    assert_eq!(out.status.code(), Some(2), "{}", stdout(&out));
    assert!(String::from_utf8_lossy(&out.stderr).contains("lacks the column 'license'"));

    let repo = clean_repo("badlock");
    write(&repo.0, "a/Cargo.lock", "[[package]]\nname = \"syn\"\n");
    assert_eq!(check(&repo).status.code(), Some(2));

    let out = Command::new(bin()).arg("verify").output().unwrap();
    assert_eq!(out.status.code(), Some(2));
    let out = Command::new(bin())
        .args(["check", "--repo"])
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(2));
}
