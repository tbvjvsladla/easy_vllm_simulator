#!/usr/bin/env python3
"""Mechanical Sub N/A list for `parity compare --na-list` (main-side tool; never delivered to run on a Sub).

A case is N/A for a topology when its entry point is not in that topology's rendered Sub tree, i.e. the Sub is not
designed to receive it. Source of truth = the render result, not a hand list. Entries under `<crate>/target/release/`
are judged by the crate's Cargo.toml (the ELF only exists after the Sub builds it).

Regenerate (main, from the repo root; commit the output):
  T=$(mktemp -d)   # outside the repo
  python3 -B .claude/skills/terraforming_node/scripts/render_sub_env.py --topology single --out $T/single   # multi: render from a multi-node checkout
  python3 -B .claude/rust/parity/sub_na/gen_na_list.py --tree $T/single --out .claude/rust/parity/sub_na/single.txt
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CASES = os.path.join(os.path.dirname(HERE), "cases")


def present(tree: str, entry: str) -> bool:
    marker = "/target/release/"
    if marker in entry:
        return os.path.isfile(os.path.join(tree, entry.split(marker)[0], "Cargo.toml"))
    return os.path.exists(os.path.join(tree, entry))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if not os.path.isdir(os.path.join(a.tree, ".claude")):
        print("tree has no .claude — not a rendered Sub tree", file=sys.stderr)
        return 2
    rows = []
    for stage in ("s1", "s2", "s3", "s4"):
        with open(os.path.join(CASES, stage + ".json"), encoding="utf-8") as f:
            for c in json.load(f):
                if not present(a.tree, c["entry"]):
                    rows.append((c["id"], c["entry"]))
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("# Sub N/A list — cases whose entry point is not in the rendered Sub tree. Generated by gen_na_list.py; do not hand-edit.\n")
        for cid, e in rows:
            f.write(f"{cid} {e}\n")
    print(f"{a.out}: {len(rows)} N/A cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
