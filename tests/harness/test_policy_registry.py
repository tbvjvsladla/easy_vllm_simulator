def _auto_manifest(doc: dict, repo_root: Path = REPO_ROOT, extra=()) -> dict:
    """Every real on-disk file an evidence.*.path or removal_evidence.path in `doc` cites gets
    its own freshly-computed, currently-correct sha256 -- see module docstring."""
    manifest: dict = {}
    for p in doc.get("policies", []):
        for e in (p.get("evidence") or []):
            if isinstance(e, dict) and isinstance(e.get("path"), str):
                full = repo_root / e["path"]
                if full.is_file():
                    manifest[e["path"]] = pr._sha256_file(full)
        removal = p.get("removal_evidence")
        if isinstance(removal, dict) and isinstance(removal.get("path"), str):
            full = repo_root / removal["path"]
            if full.is_file():
                manifest[removal["path"]] = pr._sha256_file(full)
    for rel in extra:
        full = repo_root / rel
        if full.is_file():
            manifest[rel] = pr._sha256_file(full)
    return manifest


def _lifecycle_violations(doc: dict, as_of: datetime.date = AS_OF, evidence_manifest: dict | None = None):
    if evidence_manifest is None:
        evidence_manifest = _auto_manifest(doc)
    return pr.evaluate_lifecycle(doc, as_of, repo_root=REPO_ROOT, evidence_manifest=evidence_manifest)


def _check_removal(doc: dict, policy_id: str):
    manifest = _auto_manifest(doc)
    policy = next(p for p in doc["policies"] if p["policy_id"] == policy_id)
    return pr.check_removal_eligibility(policy, repo_root=REPO_ROOT, evidence_manifest=manifest)


def _check_removal_full(doc: dict, policy_id: str, as_of: datetime.date = AS_OF):
    manifest = _auto_manifest(doc)
    selected = next(p for p in doc["policies"] if p["policy_id"] == policy_id)
    removal_rel = selected.get("removal_evidence", {}).get("path", REMOVAL_ARTIFACT_REL_PATH)
    tracked = copy.deepcopy(pr.load_tracked_index())
    tracked["entries"][removal_rel] = "0" * 40
    original = pr._git_staged_blob_sha
    def staged(root, rel):
        return "0" * 40 if rel == removal_rel else original(root, rel)
    with mock.patch.object(pr, "_git_staged_blob_sha", side_effect=staged):
        return pr.check_removal_full(doc, policy_id, as_of, SCHEMA, REPO_ROOT, manifest,
                                     tracked_index=tracked)


def _write_matching_removal_artifact(doc: dict, policy_id: str, as_of: datetime.date,
                                      corrupt_tree: bool = False):
    """Writes a temp removal-artifact JSON under RUNTIME_SCRATCH_DIR whose tree_sha256 exactly
    equals what check_removal_full will independently (re)compute for THIS doc/schema/
    evidence_manifest/claim_bindings/tracked_index -- see RUNTIME_SCRATCH_DIR's module-level
    comment for why this beats hand-maintaining a static precomputed digest fixture. Returns
    (rel_path, evidence_manifest_with_artifact_entry). When corrupt_tree, the artifact's
    tree_sha256 is deliberately wrong (a well-formed but non-matching 64-hex digest)."""
    RUNTIME_SCRATCH_DIR.mkdir(parents=True, exist_ok=True)
    artifact_path = RUNTIME_SCRATCH_DIR / f"artifact_{policy_id}.json"
    rel_path = str(artifact_path.relative_to(REPO_ROOT))
    selected = next(p for p in doc["policies"] if p["policy_id"] == policy_id)
    selected["removal_evidence"]["path"] = rel_path
    artifact_path.write_text("{}\n", encoding="utf-8")
    evidence_manifest = _auto_manifest(doc)
    claim_bindings = pr.load_claim_bindings()
    tracked_index = copy.deepcopy(pr.load_tracked_index())
    tracked_index["entries"][rel_path] = "0" * 40
    tree = pr.compute_contract_tree_sha256(
        doc, SCHEMA, evidence_manifest, claim_bindings, tracked_index, REPO_ROOT,
        selected_removal_artifact_path=rel_path)
    if corrupt_tree:
        tree = ("0" if tree[0] != "0" else "1") + tree[1:]
    artifact_path.write_text(json.dumps({
        "policy_id": policy_id, "result": "PASS", "as_of": as_of.isoformat(), "tree_sha256": tree,
    }), encoding="utf-8")
    evidence_manifest[rel_path] = pr._sha256_file(artifact_path)
    return rel_path, evidence_manifest


def _codes(violations) -> list:
    return sorted(v.reason_code for v in violations)


def _find(violations, reason_code, policy_id=None, clause_id=None, path=None):
    for v in violations:
        if v.reason_code != reason_code:
            continue
        if policy_id is not None and v.policy_id != policy_id:
            continue
        if clause_id is not None and v.clause_id != clause_id:
            continue
        if path is not None and v.path != path:
            continue
        return v
    return None


def _real_registry_lifecycle_violations():
    # Uses the COMMITTED evidence_manifest.json/tracked_index.json/claim_bindings.json
    # (evidence_manifest=None -> default load; tracked_index/claim_bindings explicitly loaded and
    # passed here) -- this exercises the SAME full check set the actual production `cmd_verify`
    # path always runs (cycle4: tracked-index ambient-git binding + clause-specific claim
    # bindings), unlike the fixture-level auto-manifest helper above (which never opts into either
    # -- see scripts/policy_registry.py module docstring "Tracked-index trust tiers" /
    # "Clause-specific claim bindings" for why that's a deliberate, safe default for fixtures).
    return pr.evaluate_lifecycle(_load_registry(), AS_OF, REPO_ROOT,
                                  tracked_index=pr.load_tracked_index(), claim_bindings=pr.load_claim_bindings())


def _real_registry_schema_violations():
    return _schema_violations(_load_registry())


