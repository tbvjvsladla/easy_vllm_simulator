class TestClaimBindingEnforcement(unittest.TestCase):
    """cycle4 fix (subagent-summary-1 finding 2 / cycle3 finding 2): a real, digest-matching,
    exact identifier's mere EXISTENCE in some cited file is not enough to "support" an arbitrary
    clause that happens to reference it -- `.claude/policies/claim_bindings.json` pre-registers
    the EXACT allowed (path, assertion_id) predicate set per clause_id; this is the mechanism that
    replaces the old (removed) `test_korean_only_clause_with_real_assertion_id_still_validates`,
    which explicitly locked the bypass in as accepted behavior."""

    def test_unrelated_korean_clause_backed_by_a_real_but_unbound_assertion_id_fails_claim_binding(self):
        # Exact cycle3 reproduction: a semantically unrelated Korean clause backed by
        # scripts/policy_registry.py:evaluate_lifecycle (a real, digest-matching identifier) --
        # this time WITH claim_bindings opted in, and evaluate_lifecycle registers a DIFFERENT
        # (path, assertion_id) pair as the only one this clause is allowed to cite.
        policies = [{"policy_id": "TEST_RES", "clauses": [{"clause_id": "TEST_RES.C1", "statement": "한국어로만 적힌 조항"}],
                     "evidence": [{"path": "scripts/policy_registry.py", "supports": ["TEST_RES.C1"],
                                    "assertion_ids": ["evaluate_lifecycle"]}]}]
